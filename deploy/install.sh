#!/usr/bin/env bash
# Keplura one-command server install (SERVER-PAKET, ADR-0010).
#
#   cd deploy && ./install.sh [--admin-email admin@firma.example] [--gpu]
#
# 1. creates .env.production from the template on first run, with random
#    DB password, secrets master key and first-admin password (kept only in
#    .env.production, never printed into terminal logs);
# 2. builds + starts db, ollama, model pull (chat + bge-m3) and server;
# 3. waits until /api/v1/health answers UP.
# Re-running is safe: an existing .env.production is never overwritten.
set -euo pipefail
cd "$(dirname "$0")"

ADMIN_EMAIL="admin@keplura.local"
HOST_PORT=""
FILES=(-f compose.prod.yml)
fail() { printf '%s\n' "$*" >&2; exit 2; }
usage() {
  echo 'Aufruf: ./install.sh [--admin-email admin@firma.example] [--port 8080] [--gpu]'
}
while [ $# -gt 0 ]; do
  case "$1" in
    --admin-email)
      [ $# -ge 2 ] && [[ "$2" =~ ^[a-zA-Z0-9._+%-]+@[a-zA-Z0-9.-]+$ ]] || fail 'Bitte eine gültige Admin-E-Mail angeben.'
      ADMIN_EMAIL="$2"; shift 2 ;;
    --port)
      [ $# -ge 2 ] && [[ "$2" =~ ^[0-9]{1,5}$ ]] || fail 'Bitte einen Port von 1 bis 65535 angeben.'
      HOST_PORT="$((10#$2))"
      [ "$HOST_PORT" -ge 1 ] && [ "$HOST_PORT" -le 65535 ] || fail 'Bitte einen Port von 1 bis 65535 angeben.'
      shift 2 ;;
    --gpu) FILES+=(-f compose.gpu.yml); shift ;;
    --help|-h) usage; exit 0 ;;
    *) usage >&2; fail "Unbekannte Option: $1" ;;
  esac
done

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
  docker info >/dev/null 2>&1 || fail 'Docker ist nicht bereit. Bitte Docker starten und erneut ausführen.'
elif command -v podman-compose >/dev/null 2>&1; then
  COMPOSE=(podman-compose)
  podman info >/dev/null 2>&1 || fail 'Podman ist nicht bereit. Bitte Podman starten und erneut ausführen.'
else fail 'Docker Compose oder podman-compose wird benötigt.'; fi
for tool in openssl curl; do
  command -v "$tool" >/dev/null || fail "Benötigtes Programm fehlt: $tool"
done

ENV_FILE=.env.production
[ ! -L "$ENV_FILE" ] || fail '.env.production darf kein symbolischer Link sein.'
if [ ! -f "$ENV_FILE" ]; then
  umask 077
  ADMIN_PW="$(openssl rand -base64 18 | tr -d '/+=' )"
  sed -e "s|^POSTGRES_PASSWORD=.*|POSTGRES_PASSWORD=$(openssl rand -hex 24)|" \
      .env.production.example > "$ENV_FILE"
  {
    echo ""
    echo "# --- generated by install.sh $(date -u +%Y-%m-%dT%H:%MZ) ---"
    echo "KEPLURA_SECRETS_MASTER_KEY=$(openssl rand -base64 32)"
    echo "KEPLURA_ADMIN_BOOTSTRAP_EMAIL=$ADMIN_EMAIL"
    echo "KEPLURA_ADMIN_BOOTSTRAP_PASSWORD=$ADMIN_PW"
  } >> "$ENV_FILE"
  echo "Zugangsdaten wurden in $ENV_FILE gespeichert (nur für den Besitzer lesbar)."
  echo 'Zum Anmelden die Werte KEPLURA_ADMIN_BOOTSTRAP_EMAIL und KEPLURA_ADMIN_BOOTSTRAP_PASSWORD verwenden.'
else
  echo "$ENV_FILE ist vorhanden. Bestehende Zugangsdaten bleiben erhalten."
  # Umbenennung IntraCore -> Keplura (ADR-0013): alte Schlüsselnamen einmalig
  # umschreiben, Werte unverändert, Sicherung mit gleichen Rechten daneben.
  if grep -Eq '^(export[[:space:]]+)?INTRACORE_' "$ENV_FILE"; then
    BACKUP="$ENV_FILE.vor-keplura"
    # eine frühere Sicherung nie überschreiben
    if [ -e "$BACKUP" ] || [ -L "$BACKUP" ]; then BACKUP="$ENV_FILE.vor-keplura.$(date -u +%Y%m%dT%H%M%SZ)"; fi
    [ ! -L "$BACKUP" ] || fail '.env.production-Sicherung darf kein symbolischer Link sein.'
    cp -p "$ENV_FILE" "$BACKUP"
    # INTRACORE_X -> KEPLURA_X (auch mit `export `); steht KEPLURA_X schon
    # drin, gewinnt der neue Name und die alte Zeile entfällt.
    tmp="$(mktemp "$ENV_FILE.XXXXXX")"
    trap 'rm -f "$tmp"' EXIT
    awk '
      FNR==NR { if (match($0, /^(export[ 	]+)?KEPLURA_[A-Za-z0-9_]+=/)) { k=substr($0, RSTART, RLENGTH); sub(/^export[ 	]+/, "", k); have[k]=1 } next }
      match($0, /^(export[ 	]+)?INTRACORE_[A-Za-z0-9_]+=/) {
        pre=substr($0, RSTART, RLENGTH); k=pre; sub(/^export[ 	]+/, "", k); sub(/^INTRACORE_/, "KEPLURA_", k)
        if (k in have) next
        sub(/INTRACORE_/, "KEPLURA_")
      }
      { print }
    ' "$ENV_FILE" "$ENV_FILE" > "$tmp"
    chmod --reference="$ENV_FILE" "$tmp" 2>/dev/null || chmod 600 "$tmp"
    chown --reference="$ENV_FILE" "$tmp" 2>/dev/null || true
    mv -f "$tmp" "$ENV_FILE"
    trap - EXIT
    echo "Alte INTRACORE_-Einträge in $ENV_FILE auf KEPLURA_ umbenannt (Sicherung: $BACKUP)."
  fi
fi

# An explicit port changes only this invocation, never existing credentials.
# Export it so Compose and the health probe resolve the same value.
if [ -n "$HOST_PORT" ]; then export KEPLURA_SERVER_HOST_PORT="$HOST_PORT"; fi
PORT="${KEPLURA_SERVER_HOST_PORT:-$(sed -n 's/^KEPLURA_SERVER_HOST_PORT=//p' "$ENV_FILE" | tail -n 1 | tr -d '\r')}"
PORT="${PORT:-8080}"
[[ "$PORT" =~ ^[0-9]{1,5}$ ]] || fail 'Ungültiger Server-Port in der Konfiguration.'
PORT="$((10#$PORT))"
[ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || fail 'Ungültiger Server-Port in der Konfiguration.'

echo 'Installation startet: Server bauen und Modelle herunterladen. Das kann beim ersten Mal länger dauern.'
"${COMPOSE[@]}" "${FILES[@]}" --env-file "$ENV_FILE" up -d --build

for i in $(seq 1 120); do
  if curl --connect-timeout 2 --max-time 5 -fsS "http://127.0.0.1:$PORT/api/v1/health" >/dev/null 2>&1; then
    echo "Keplura ist erreichbar: http://localhost:$PORT/"
    echo 'Für den Zugriff im Firmennetz HTTPS mit einem Reverse-Proxy einrichten (deploy/README.md).'
    exit 0
  fi
  sleep 5
done
echo "Server ist noch nicht bereit. Diagnose: ${COMPOSE[*]} ${FILES[*]} --env-file $ENV_FILE logs --tail 80 server ollama-pull" >&2
exit 1
