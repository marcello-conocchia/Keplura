#!/usr/bin/env node
// Third-party license inventory (OPEN-SOURCE-01).
//
// Writes a Markdown report of every runtime dependency of the three shipped
// components and its declared license:
//   - desktop/web UI   : desktop/package-lock.json (dev-only packages excluded)
//   - Tauri shell      : `cargo metadata` in desktop/src-tauri (all targets)
//   - local reader     : `cargo metadata` in server/native/local-reader
//   - server           : `mvn dependency:list` (runtime scope) + POMs in ~/.m2
//
// Usage (repo root; needs node, cargo and mvn on PATH, network for the first
// cargo/mvn resolution):
//   node scripts/third-party-licenses.cjs > docs/legal/THIRD_PARTY_LICENSES.md
//
// The report lists DECLARED licenses only (package metadata). It is an
// inventory for review, not legal advice; entries marked UNKNOWN need a
// manual look.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const run = (cmd, cwd) => execSync(cmd, { cwd, maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }).toString();

function npmPackages() {
  const dir = path.join(root, 'desktop');
  const lock = JSON.parse(fs.readFileSync(path.join(dir, 'package-lock.json'), 'utf8'));
  const out = [];
  for (const [p, v] of Object.entries(lock.packages || {})) {
    if (!p || v.dev) continue;
    let lic = v.license;
    if (!lic) {
      try { lic = JSON.parse(fs.readFileSync(path.join(dir, p, 'package.json'), 'utf8')).license; } catch { /* not installed */ }
    }
    if (lic && typeof lic === 'object') lic = lic.type;
    out.push({ name: p.replace(/.*node_modules\//, ''), version: v.version, license: lic || 'UNKNOWN' });
  }
  return out;
}

function cargoPackages(rel) {
  const meta = JSON.parse(run('cargo metadata --format-version 1 --locked', path.join(root, rel)));
  const own = new Set(meta.workspace_members);
  return meta.packages.filter((p) => !own.has(p.id))
    .map((p) => ({ name: p.name, version: p.version, license: p.license || (p.license_file ? 'see ' + p.license_file : 'UNKNOWN') }));
}

function mavenPackages() {
  const tmp = path.join(os.tmpdir(), 'keplura-mvn-deps.txt');
  run(`mvn -q -B dependency:list -DincludeScope=runtime -DoutputFile="${tmp}"`, path.join(root, 'server'));
  const m2 = path.join(os.homedir(), '.m2', 'repository');
  const pom = (g, a, v) => path.join(m2, ...g.split('.'), a, v, `${a}-${v}.pom`);
  const licenseOf = (g, a, v, depth = 0) => {
    const f = pom(g, a, v);
    if (depth > 8 || !fs.existsSync(f)) return null;
    const x = fs.readFileSync(f, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
    const ls = x.match(/<licenses>([\s\S]*?)<\/licenses>/);
    if (ls) return [...ls[1].matchAll(/<name>\s*([\s\S]*?)\s*<\/name>/g)].map((m) => m[1].replace(/\s+/g, ' ')).join(' OR ');
    const parent = x.match(/<parent>([\s\S]*?)<\/parent>/);
    if (!parent) return null;
    const get = (t) => (parent[1].match(new RegExp(`<${t}>\\s*([^<]+?)\\s*</${t}>`)) || [])[1];
    return licenseOf(get('groupId'), get('artifactId'), get('version'), depth + 1);
  };
  return fs.readFileSync(tmp, 'utf8').split('\n').map((l) => l.trim()).filter((l) => /^[\w.-]+:[\w.-]+:/.test(l))
    .map((l) => { const [g, a, , v] = l.split(' ')[0].split(':'); return { name: `${g}:${a}`, version: v, license: licenseOf(g, a, v) || 'UNKNOWN' }; });
}

function section(title, pkgs) {
  const byLic = {};
  for (const p of pkgs) (byLic[p.license] ??= []).push(p);
  const rows = Object.entries(byLic).sort((a, b) => b[1].length - a[1].length);
  let s = `## ${title}\n\n${pkgs.length} packages.\n\n| License (as declared) | Count |\n|---|---|\n`;
  for (const [l, ps] of rows) s += `| ${l.replace(/\|/g, '/')} | ${ps.length} |\n`;
  s += '\n<details><summary>Full list</summary>\n\n| Package | Version | License |\n|---|---|---|\n';
  for (const p of [...pkgs].sort((a, b) => a.name.localeCompare(b.name))) s += `| ${p.name} | ${p.version} | ${p.license.replace(/\|/g, '/')} |\n`;
  return s + '\n</details>\n\n';
}

let md = '# Third-party licenses (inventory)\n\n';
md += 'Generated by `node scripts/third-party-licenses.cjs`. Lists the licenses the\n';
md += 'packages DECLARE in their metadata, for review; it is not legal advice.\n';
md += 'Build-only tooling (Maven plugins, npm devDependencies, Rust build tools that\n';
md += 'are not linked) is excluded unless the package manager reports it as runtime.\n\n';
md += section('Web / desktop UI (npm, production dependencies)', npmPackages());
md += section('Desktop shell (Rust crates, desktop/src-tauri, all target platforms)', cargoPackages('desktop/src-tauri'));
md += section('Local source reader (Rust crates, server/native/local-reader)', cargoPackages('server/native/local-reader'));
md += section('Server (Maven, runtime scope)', mavenPackages());
process.stdout.write(md);
