-- M3a baseline schema (ADR-0006) — single source of truth for the prod/PostgreSQL schema.
--
-- Derived from the Hibernate-generated schema of this exact entity set (User,
-- Organization, Membership) verified against a real PostgreSQL 16.15 + pgvector
-- 0.6.0 instance (pg_dump of a ddl-auto=create boot), and kept executable by
-- H2 as well so the migration can be regression-tested without a container.
-- Therefore only portable SQL constructs are used (identity columns,
-- timestamp(6) with time zone, named constraints) — no pg_dump noise, no
-- schema qualification (PG resolves via search_path, H2 uses PUBLIC).
--
-- Deliberately NOT in the baseline:
--   * No CREATE EXTENSION vector / embedding columns — pgvector usage is M3b.
--   * No foreign keys on membership(org_id,user_id): the entities model plain
--     columns (authorization is enforced in the repository layer, ADR-0004),
--     and Hibernate ddl-auto=validate does not expect FKs. Introducing them
--     would itself be a schema-drift event — future migration, separate ADR.

CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email character varying(320) NOT NULL,
    password_hash character varying(200) NOT NULL,
    display_name character varying(200) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT app_user_pkey PRIMARY KEY (id),
    CONSTRAINT app_user_email_key UNIQUE (email)
);

CREATE TABLE organization (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name character varying(200) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT organization_pkey PRIMARY KEY (id)
);

CREATE TABLE membership (
    org_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role character varying(20) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT membership_pkey PRIMARY KEY (org_id, user_id)
);
