-- M4b: Chat persistence — conversations and messages per user inside a space.
-- V1–V5 stay untouched (their Flyway checksums must never change; schema
-- evolves by NEW migrations only, ADR-0006).
--
-- Same portability rules as every earlier migration: identity columns,
-- timestamp(6) with time zone, named constraints, no FK constraints, no
-- vendor syntax — executable by PostgreSQL (prod, Flyway-owned schema) AND H2
-- in PostgreSQL mode, and matching Hibernate ddl-auto=validate.
--
-- Authorization model (ADR-0004 carry-over, same deliberate MVP decision as
-- V2/V3): org membership IS the ACL; no chat_share / chat_member tables.
-- Chat is personal per user WITHIN a space: conversation carries created_by
-- (the only-user-visible filter, enforced at query level in ChatRepository),
-- org_id and space_id are the tenant pins every read re-checks. No FKs —
-- plain bigint columns, same rationale as V2–V4.
--
-- knowledge_base_id is NULL for plain conversations: no RAG context, no
-- citations. When set it pins the kb whose chunks ground the answers (kb is
-- itself pinned to space/org — the kb chain is re-proven on every message).

CREATE TABLE chat_conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    created_by bigint NOT NULL,
    -- optional RAG context (M3 kb); NULL = plain chat without citations
    knowledge_base_id bigint,
    -- conversation list label (server-derived from the first question)
    title character varying(200) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT chat_conversation_pkey PRIMARY KEY (id)
);

-- the list read is "my conversations in this space", newest first
CREATE INDEX chat_conversation_org_id_created_by_space_id_idx
    ON chat_conversation (org_id, created_by, space_id);

CREATE TABLE chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    conversation_id bigint NOT NULL,
    -- user | assistant (validated at the service boundary; no enum type in
    -- the portable schema, same stance as knowledge_base naming)
    role character varying(16) NOT NULL,
    -- the visible text: prompt echo, streamed answer (complete or partial),
    -- or the error note of an aborted turn. Capped server-side.
    content character varying(32000) NOT NULL,
    -- server-side model tag that produced an assistant row ("" for user rows);
    -- an audit fact, never an upstream URL or key.
    model character varying(128) NOT NULL,
    -- JSON array of citation entries (documentId/filename/chunkIdx/score of
    -- the RAG hits); "[]" when the turn had no knowledge context.
    citations_json character varying(16000) NOT NULL,
    -- honest end state of an assistant turn: complete | aborted | failed |
    -- incomplete; "complete" for user rows (varchar kept portable, no enum
    -- types). Rows are written once at turn end — a crashed mid-turn leaves
    -- NO assistant row at all, which is the truthful history.
    status character varying(16) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT chat_message_pkey PRIMARY KEY (id)
);

-- the transcript read is "messages of one conversation in id order"
CREATE INDEX chat_message_conversation_id_idx
    ON chat_message (conversation_id);
