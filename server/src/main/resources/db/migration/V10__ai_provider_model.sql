-- ADMIN-KI SCOPE B/C (docs/adr/0008 §3): KI provider + model rows — the
-- deployment-level AI configuration that replaces .env-only provider upkeep.
--
-- Global deployment resource on purpose (ADR-0008 §3): NO org_id column.
-- One backend per installation, like the ENV config today; per-org providers
-- would be new scope without a PO request.
--
-- Same portability rules as V1–V9: identity columns, timestamp(6) with time
-- zone, named constraints, no FKs (authorization and integrity live in the
-- service layer — same deliberate MVP decision as every previous table), and
-- no partial indexes (not H2-portable; default-slot consistency is enforced
-- transactionally in AiModelService).
--
-- secret_cipher stores AES-GCM ciphertext (Base64) produced by SecretCipher
-- with the .env master key — the plaintext API key NEVER exists in the
-- schema, in a log line, or in an API response (ADR-0008 §4). NULL = no
-- secret set.
--
-- default_slot: a computed, DB-enforced "at most one default per model type".
-- AiModelService keeps it in sync transactionally (set to the id of the
-- default row, NULL otherwise); the UNIQUE constraint makes an inconsistent
-- double-default impossible even under a race. Portable (plain nullable
-- column + unique constraint), unlike a partial index.

CREATE TABLE ai_provider (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- display name (operator-facing, never secret)
    name character varying(200) NOT NULL,
    -- provider vocabulary == ProviderPreset ids: ollama | vllm | api
    -- (CHECK keeps junk out of the schema; the service answers 400 before
    -- the DB ever sees a violation)
    provider_type character varying(20) NOT NULL,
    -- OpenAI-compatible base URL; may name a LAN host — never surfaced to
    -- the UI (system-status projects booleans only, ADR-0008 §7)
    base_url character varying(500) NOT NULL,
    secret_cipher character varying(1000),
    timeout_seconds integer NOT NULL DEFAULT 30,
    enabled boolean NOT NULL DEFAULT TRUE,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ai_provider_pkey PRIMARY KEY (id),
    CONSTRAINT ai_provider_name_key UNIQUE (name),
    CONSTRAINT ai_provider_type_check
        CHECK (provider_type IN ('ollama', 'vllm', 'api')),
    CONSTRAINT ai_provider_timeout_check CHECK (timeout_seconds BETWEEN 1 AND 300)
);

CREATE TABLE ai_model (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider_id bigint NOT NULL,
    name character varying(200) NOT NULL,
    -- upstream model identifier (e.g. qwen2.5:0.5b) — not a secret, but
    -- never sent to unauthenticated surfaces
    technical_model_id character varying(300) NOT NULL,
    model_type character varying(20) NOT NULL,
    -- EMBEDDING only; changing it has INDEX consequences (pgvector twin
    -- column) — the UI shows it, it is NOT editable after creation, and a
    -- model switch never triggers re-indexing (Scope D).
    embedding_dim integer,
    max_output_tokens integer,
    temperature numeric(4,3),
    enabled boolean NOT NULL DEFAULT TRUE,
    is_default boolean NOT NULL DEFAULT FALSE,
    default_slot bigint,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ai_model_pkey PRIMARY KEY (id),
    CONSTRAINT ai_model_type_check CHECK (model_type IN ('CHAT', 'EMBEDDING')),
    CONSTRAINT ai_model_temperature_check
        CHECK (temperature IS NULL OR (temperature >= 0 AND temperature <= 2)),
    -- the DB-side guard described above: (model_type) WHERE default_slot
    -- NOT NULL is unique, expressed portably as a unique column pair.
    CONSTRAINT ai_model_default_slot_key UNIQUE (model_type, default_slot)
);
