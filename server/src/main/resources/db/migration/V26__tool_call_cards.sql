-- TU-02 (PO-Auftrag 21.11.2026): Aufrufkarten und konkrete Bestätigungen.
-- Eine Zeile je geplantem Werkzeugaufruf eines Chat-Turns. Ein CRITICAL-Aufruf wartet hier als PENDING;
-- die Zeile bindet Person, Organisation, Arbeitsbereich, Chat, Werkzeugdefinition (Hash inkl. Risikoklasse,
-- Schema und Ziel-/Token-Fingerprint) und die exakt geplanten Argumente. Keine Zugangsdaten.
CREATE TABLE tool_call (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id character varying(36) NOT NULL,
    conversation_id bigint NOT NULL,
    prompt_message_id bigint,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    adapter character varying(32) NOT NULL,
    tool_id character varying(300) NOT NULL,
    function_name character varying(64) NOT NULL,
    tool_name character varying(128) NOT NULL,
    source_id bigint,
    source_name character varying(120) NOT NULL,
    risk character varying(16),
    definition_hash character varying(64) NOT NULL,
    fingerprint character varying(64),
    arguments_json character varying(16000) NOT NULL,
    status character varying(16) NOT NULL,
    needs_confirmation boolean NOT NULL,
    result_text character varying(9000),
    error character varying(300),
    created_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone,
    decided_at timestamp with time zone,
    started_at timestamp with time zone,
    finished_at timestamp with time zone,
    CONSTRAINT tool_call_pkey PRIMARY KEY (id),
    CONSTRAINT tool_call_public_id_key UNIQUE (public_id)
);
CREATE INDEX tool_call_conversation_idx ON tool_call (conversation_id, created_at);

-- Audit-Zeile ↔ Karte (nachvollziehbar, weiterhin ohne Argumente/Ergebnisse im Protokoll).
ALTER TABLE tool_call_log ADD COLUMN tool_call_id bigint;
