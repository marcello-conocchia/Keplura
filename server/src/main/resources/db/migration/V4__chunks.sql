-- M3d (part 1): searchable chunks for the RAG query path — PORTABLE SQL only
-- (same rules as V1–V3: identity columns, timestamp(6) with time zone, named
-- constraints, no FK constraints, no vendor syntax — executable by PostgreSQL
-- AND H2 in PostgreSQL mode, and matching Hibernate ddl-auto=validate).
--
-- This table is the database-independent half of the vector store: chunk TEXT
-- (the citation payload) plus a canonical JSON encoding of the embedding,
-- which keeps the H2/dev/test path restart-safe with in-JVM cosine
-- similarity. On PostgreSQL WITH the extension, the native `vector(N)` twin
-- table kb_chunk_embedding (db/migration-postgresql/V5__pgvector.sql) is
-- populated alongside and backs real KNN. See docs/adr/0007 for the store
-- strategy; a single vector(N) column here was NOT possible because the
-- portable replay and the H2 smoke fallback would both have to understand
-- pgvector.
--
-- Like V3, rows carry plain bigint pins without FOREIGN KEY constraints
-- (entities model plain columns; ddl-auto=validate does not expect FKs).

CREATE TABLE kb_chunk (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    document_id bigint NOT NULL,
    -- denormalised kb pin: EVERY search read filters by knowledge_base_id
    -- FIRST (tenant gate before similarity ranking), so the join to
    -- kb_document only ever happens for the caller-visible topK rows.
    knowledge_base_id bigint NOT NULL,
    -- 0-based position of the chunk inside its document (source citation!)
    chunk_idx integer NOT NULL,
    -- chunker guarantees chunks are <= chunk-size-chars (default 800); the
    -- column keeps a hard DB bound (4000) so no future config drift can
    -- smuggle unbounded text into the table. Named chunk_text: "text" is a
    -- type keyword and an accident waiting to happen in H2/PG quoting.
    chunk_text character varying(4000) NOT NULL,
    -- canonical embedding encoding: comma-separated Float.toString values in
    -- [ ] brackets (pgvector text literal format). Portable storage of truth;
    -- the pgvector table is derived data (see ADR-0007).
    embedding character varying(65536) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT kb_chunk_pkey PRIMARY KEY (id),
    -- idempotent re-indexing anchor: one chunk position per document, ever
    CONSTRAINT kb_chunk_document_id_chunk_idx_key UNIQUE (document_id, chunk_idx)
);

-- the ONLY filter the search path applies before ranking: chunks of one kb
CREATE INDEX kb_chunk_knowledge_base_id_idx
    ON kb_chunk (knowledge_base_id);
