-- SEC-2: organization invites — one-time, expiring membership grants.
-- V1–V7 stay untouched (their Flyway checksums must never change; schema
-- evolves by NEW migrations only, ADR-0006).
--
-- Same portability rules as every earlier migration: identity columns,
-- timestamp(6) with time zone, named constraints, no FK constraints, no
-- vendor syntax — executable by PostgreSQL (prod, Flyway-owned schema) AND H2
-- in PostgreSQL mode, and matching Hibernate ddl-auto=validate.
--
-- The token is stored ONLY as its SHA-256 hex digest (token_hash): a DB leak
-- can never hand out membership, and the plaintext is shown exactly once in
-- the create response. One-time use is modelled as used_at: redemption is an
-- atomic conditional UPDATE (SET used_at/used_by WHERE used_at IS NULL AND
-- not expired) in InviteService.accept, so concurrent accepts of the same
-- token serialise on the row and EXACTLY ONE updates it — the UNIQUE digest
-- alone would NOT do that (it constrains two rows sharing a hash, not two
-- redemptions of one row; see FINDING-1 on PR #29 and the latch-synchronized
-- two-accepts test). A duplicate membership grant additionally fails on the
-- membership PK. No FKs on org_id/inviter_id — plain bigint columns, same
-- rationale as V1–V4.

CREATE TABLE org_invite (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    inviter_id bigint NOT NULL,
    -- sha256 hex of the plaintext token (64 chars); UNIQUE = the one-time anchor
    token_hash character varying(64) NOT NULL,
    -- membership role the redemption grants; CHECK clamps the vocabulary.
    -- MEMBER is the ONLY value the service can ever write (accept-by-invite
    -- must structurally never mint an OWNER — an escalation path must not
    -- exist even as a hand-edited row).
    role character varying(20) NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    -- NULL until redeemed (revocation deletes the row outright, so a
    -- used_at stamp is the only terminal fact that needs persistence).
    used_at timestamp(6) with time zone,
    used_by bigint,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT org_invite_pkey PRIMARY KEY (id),
    CONSTRAINT org_invite_token_hash_key UNIQUE (token_hash),
    CONSTRAINT org_invite_role_check CHECK (role = 'MEMBER')
);

-- the OWNER pending list is "invites of this org, newest first"
CREATE INDEX org_invite_org_id_idx ON org_invite (org_id, created_at);
