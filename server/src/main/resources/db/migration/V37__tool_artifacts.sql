-- TU-06d: image and file results of tool calls. Bytes are stored only after the type was verified by magic bytes
-- (allowlist; no SVG/HTML/executables) and within the size and count limits; a dropped artifact keeps only its
-- fixed reason (data NULL) so the card can show it. Deleted with its card (and therefore with the chat).
-- No CHECK constraints on purpose: the store validates and fails closed.
CREATE TABLE tool_artifact (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id character varying(36) NOT NULL,
    tool_call_id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    prompt_message_id bigint,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    name character varying(120) NOT NULL,
    media_type character varying(64),
    size_bytes bigint NOT NULL,
    sha256 character varying(64),
    data bytea,
    dropped_reason character varying(300),
    internal boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT tool_artifact_pkey PRIMARY KEY (id),
    CONSTRAINT tool_artifact_public UNIQUE (public_id),
    CONSTRAINT fk_tool_artifact_call FOREIGN KEY (tool_call_id) REFERENCES tool_call (id) ON DELETE CASCADE
);
CREATE INDEX tool_artifact_call_idx ON tool_artifact (tool_call_id);
CREATE INDEX tool_artifact_question_idx ON tool_artifact (conversation_id, prompt_message_id);
