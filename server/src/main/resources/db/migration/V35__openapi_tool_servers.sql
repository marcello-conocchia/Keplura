-- TU-06a: OpenAPI tool servers (admin only), analogous to mcp_server. No CHECK constraints on purpose:
-- the admin service validates auth_mode, and the adapter treats any unknown value as "not usable" (fail closed).
-- operations_json = snapshot of the parsed operations (usable and blocked ones with their reason);
-- enabled_tools = approved operationIds (lines); tool_risks = JSON object operationId -> READ/WRITE/CRITICAL.
CREATE TABLE openapi_server (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name character varying(120) NOT NULL,
    spec_url character varying(500) NOT NULL,
    base_url character varying(500) NOT NULL,
    auth_mode character varying(16) DEFAULT 'none' NOT NULL,
    token_enc character varying(4000),
    enabled boolean NOT NULL,
    all_spaces boolean DEFAULT false NOT NULL,
    operations_json text,
    enabled_tools character varying(20000),
    tool_risks character varying(20000),
    last_checked_at timestamp with time zone,
    last_error character varying(500),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT openapi_server_pkey PRIMARY KEY (id)
);

CREATE TABLE openapi_server_space (
    server_id bigint NOT NULL,
    space_id bigint NOT NULL,
    CONSTRAINT openapi_server_space_pkey PRIMARY KEY (server_id, space_id),
    CONSTRAINT fk_openapi_space_server FOREIGN KEY (server_id) REFERENCES openapi_server (id) ON DELETE CASCADE,
    CONSTRAINT fk_openapi_space_space FOREIGN KEY (space_id) REFERENCES space (id) ON DELETE CASCADE
);

-- Org boundary ("internal") exactly like mcp_org_boundary, so provenance and disclosure cards apply unchanged.
CREATE TABLE openapi_org_boundary (
    server_id bigint NOT NULL,
    org_id bigint NOT NULL,
    internal boolean DEFAULT false NOT NULL,
    revision bigint DEFAULT 0 NOT NULL,
    CONSTRAINT openapi_org_boundary_pkey PRIMARY KEY (server_id, org_id),
    CONSTRAINT fk_openapi_boundary_server FOREIGN KEY (server_id) REFERENCES openapi_server (id) ON DELETE CASCADE
);
