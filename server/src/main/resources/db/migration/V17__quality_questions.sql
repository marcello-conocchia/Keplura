-- Portable SQL (PostgreSQL + H2), keine Fremdschlüssel (Konvention V1–V16).
CREATE TABLE quality_question (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    knowledge_base_id bigint NOT NULL,
    question character varying(2000) NOT NULL,
    expected_document character varying(500) NOT NULL,
    expected_phrase character varying(500),
    created_by bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT quality_question_pkey PRIMARY KEY (id)
);
CREATE INDEX quality_question_kb_idx ON quality_question (knowledge_base_id);

CREATE TABLE quality_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    knowledge_base_id bigint NOT NULL,
    run_by bigint NOT NULL,
    started_at timestamp with time zone NOT NULL,
    finished_at timestamp with time zone,
    total integer NOT NULL,
    hits integer NOT NULL,
    CONSTRAINT quality_run_pkey PRIMARY KEY (id)
);
CREATE INDEX quality_run_kb_idx ON quality_run (knowledge_base_id);

CREATE TABLE quality_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id bigint NOT NULL,
    question_id bigint NOT NULL,
    hit boolean NOT NULL,
    hit_rank integer,
    top_document character varying(500),
    CONSTRAINT quality_result_pkey PRIMARY KEY (id)
);
CREATE INDEX quality_result_run_idx ON quality_result (run_id);
