-- M3b: Spaces — the tenant level below an organization. V1__baseline.sql stays
-- untouched (its Flyway checksum must never change; schema evolves by NEW
-- migrations only, ADR-0006).
--
-- Same portability rules as the baseline: identity columns, timestamp(6) with
-- time zone, named constraints, no schema qualification — executable by both
-- PostgreSQL (prod, Flyway-owned schema) and H2 in PostgreSQL mode (the
-- regression test replay) and matching Hibernate ddl-auto=validate.
--
-- Authorization model: there is NO space_membership table (deliberate MVP
-- decision, docs/adr/0004 carry-over): org membership IS the space ACL and is
-- enforced at query level (SpaceRepository), exactly like every org read. A
-- per-space role table would model a permission difference that does not
-- exist yet.
--
-- No foreign key on org_id: same rationale as membership(org_id,user_id) in
-- the baseline — the entity models a plain column, ddl-auto=validate does not
-- expect FKs, and adding them would itself be a schema-drift event.

CREATE TABLE space (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    name character varying(200) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT space_pkey PRIMARY KEY (id),
    -- name unique WITHIN its organization; different orgs may reuse a name
    CONSTRAINT space_org_id_name_key UNIQUE (org_id, name)
);
