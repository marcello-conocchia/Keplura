-- MCP-Server (Stufe 1, PO 14.11.2026): vom Admin eingetragen, nur HTTP-Transport (kein Prozessstart
-- auf dem Server). tools_json = zuletzt geladene Werkzeugliste; enabled_tools = freigegebene Namen (Zeilen).
CREATE TABLE mcp_server (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name character varying(120) NOT NULL,
    url character varying(500) NOT NULL,
    token_enc character varying(4000),
    enabled boolean NOT NULL,
    tools_json character varying(32000),
    enabled_tools character varying(4000),
    last_checked_at timestamp with time zone,
    last_error character varying(500),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT mcp_server_pkey PRIMARY KEY (id)
);
