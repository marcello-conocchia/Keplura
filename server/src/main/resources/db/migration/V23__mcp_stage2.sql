ALTER TABLE mcp_server ADD COLUMN all_spaces boolean DEFAULT false NOT NULL;

CREATE TABLE mcp_server_space (
    server_id bigint NOT NULL,
    space_id bigint NOT NULL,
    CONSTRAINT mcp_server_space_pkey PRIMARY KEY (server_id, space_id),
    CONSTRAINT fk_mcp_space_server FOREIGN KEY (server_id) REFERENCES mcp_server (id) ON DELETE CASCADE,
    CONSTRAINT fk_mcp_space_space FOREIGN KEY (space_id) REFERENCES space (id) ON DELETE CASCADE
);

CREATE TABLE mcp_call_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    called_at timestamp with time zone NOT NULL,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    server_id bigint NOT NULL,
    server_name character varying(120) NOT NULL,
    tool_name character varying(128) NOT NULL,
    duration_ms bigint NOT NULL,
    ok boolean NOT NULL,
    error character varying(300),
    CONSTRAINT mcp_call_log_pkey PRIMARY KEY (id)
);
CREATE INDEX mcp_call_log_time_idx ON mcp_call_log (called_at);
