-- M3c: Knowledge Bases + Document metadata — the tenant levels below a space.
-- V1/V2 stay untouched (their Flyway checksums must never change; schema
-- evolves by NEW migrations only, ADR-0006).
--
-- Same portability rules as the baseline: identity columns, timestamp(6) with
-- time zone, named constraints, no schema qualification — executable by both
-- PostgreSQL (prod, Flyway-owned schema) and H2 in PostgreSQL mode (the
-- regression replay in FlywayBaselineMigrationTest), and matching Hibernate
-- ddl-auto=validate.
--
-- Authorization model: NO knowledge_base_membership / document_acl tables —
-- org membership IS the ACL down the whole chain (ADR-0004 carry-over, same
-- deliberate MVP decision as V2/space). Membership-join + space-pin + kb-pin
-- happen in the repository queries; every table below keeps plain bigint FK
-- columns without FOREIGN KEY constraints — same rationale as V1/V2: the
-- entities model plain columns, ddl-auto=validate does not expect FKs, and
-- adding them would itself be a schema-drift event.
--
-- Deliberately NOT here (M3d): embeddings, pgvector columns, parsed text or
-- chunk tables. This migration is pure container + metadata; the file bytes
-- live on disk, referenced by stored_path (server-generated UUID path — never
-- derived from the user filename, see DocumentStorage).

CREATE TABLE knowledge_base (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    space_id bigint NOT NULL,
    name character varying(200) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT knowledge_base_pkey PRIMARY KEY (id),
    -- name unique WITHIN its space (mirrors the space-in-org rule); kb ids
    -- stay globally unique, only names are scoped
    CONSTRAINT knowledge_base_space_id_name_key UNIQUE (space_id, name)
);

CREATE TABLE kb_document (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    knowledge_base_id bigint NOT NULL,
    filename character varying(255) NOT NULL,
    content_type character varying(200) NOT NULL,
    size_bytes bigint NOT NULL,
    -- lowercase hex sha256 of the stored bytes: integrity + dedup anchor (M3d)
    sha256 character varying(64) NOT NULL,
    -- server-generated relative path under the upload base dir (UUID layout,
    -- orgs/{org}/spaces/{space}/kbs/{kb}/{uuid}); never user input
    stored_path character varying(500) NOT NULL,
    uploaded_by bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT kb_document_pkey PRIMARY KEY (id)
);

-- every list read is "documents of one kb" — the FK-lookup index backs it
CREATE INDEX kb_document_knowledge_base_id_idx
    ON kb_document (knowledge_base_id);
