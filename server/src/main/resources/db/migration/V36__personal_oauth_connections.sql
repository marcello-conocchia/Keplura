-- TU-06b: personal OAuth connections (Authorization Code + PKCE S256) for MCP (HTTP) and OpenAPI servers.
-- No CHECK constraints on purpose (H2 cannot evaluate IN-lists on the migrated schema): the service validates
-- kind and status and treats any unknown value as "no connection" (fail closed).

-- Admin client configuration per server. revision grows with every change of endpoints, client or scopes;
-- a connection is only valid for the revision it was created with.
CREATE TABLE tool_oauth_client (
    kind character varying(16) NOT NULL,
    server_id bigint NOT NULL,
    authorize_url character varying(500) NOT NULL,
    token_url character varying(500) NOT NULL,
    revoke_url character varying(500),
    client_id character varying(300) NOT NULL,
    client_secret_enc character varying(4000),
    scopes character varying(1000),
    revision bigint DEFAULT 1 NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT tool_oauth_client_pkey PRIMARY KEY (kind, server_id)
);

-- Tokens of ONE person for ONE server in ONE organization, encrypted with SecretCipher. Never shared.
CREATE TABLE tool_oauth_connection (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    kind character varying(16) NOT NULL,
    server_id bigint NOT NULL,
    client_revision bigint NOT NULL,
    access_token_enc character varying(12000) NOT NULL,
    refresh_token_enc character varying(12000),
    expires_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT tool_oauth_connection_pkey PRIMARY KEY (id),
    CONSTRAINT tool_oauth_connection_owner UNIQUE (user_id, org_id, kind, server_id)
);
CREATE INDEX tool_oauth_connection_server_idx ON tool_oauth_connection (kind, server_id);

-- One authorization attempt: state only as SHA-256, PKCE verifier and returned code encrypted,
-- bound to the starting session (hash), person, organization, server and client revision.
CREATE TABLE tool_oauth_flow (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id character varying(36) NOT NULL,
    state_hash character varying(64) NOT NULL,
    session_hash character varying(64) NOT NULL,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    kind character varying(16) NOT NULL,
    server_id bigint NOT NULL,
    client_revision bigint NOT NULL,
    verifier_enc character varying(1000) NOT NULL,
    redirect_uri character varying(600) NOT NULL,
    code_enc character varying(12000),
    status character varying(16) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    CONSTRAINT tool_oauth_flow_pkey PRIMARY KEY (id),
    CONSTRAINT tool_oauth_flow_public UNIQUE (public_id),
    CONSTRAINT tool_oauth_flow_state UNIQUE (state_hash)
);
