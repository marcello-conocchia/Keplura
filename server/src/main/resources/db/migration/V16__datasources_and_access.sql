-- Schritt 5 (ADR-0012): Datenquellen mit Rechte-Spiegelung.
-- Portable SQL (PostgreSQL + H2). Keine Fremdschlüssel — gleiche Konvention
-- wie V1–V15; jede Lesestelle prüft die Tenant-Kette selbst.

-- Kanonische Prinzipale eines Benutzers (beim Verzeichnis-Login aufgefrischt):
--   sid:S-1-5-21-…   posix-uid:1001   posix-gid:2001   ldap-dn:cn=…   entra:<id>
CREATE TABLE user_principal (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    principal character varying(300) NOT NULL,
    refreshed_at timestamp with time zone NOT NULL,
    CONSTRAINT user_principal_pkey PRIMARY KEY (id),
    CONSTRAINT user_principal_user_principal_key UNIQUE (user_id, principal)
);
CREATE INDEX user_principal_principal_idx ON user_principal (principal);

-- Effektive Leserechte je Dokument aus einer Datenquelle. Dokumente OHNE
-- Zeilen hier (Hand-Upload) bleiben für alle Mitglieder der Wissensbasis
-- sichtbar. Sonderprinzipal 'everyone' = jede angemeldete Person.
CREATE TABLE kb_document_acl (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    document_id bigint NOT NULL,
    principal character varying(300) NOT NULL,
    allow_read boolean NOT NULL,
    CONSTRAINT kb_document_acl_pkey PRIMARY KEY (id),
    CONSTRAINT kb_document_acl_entry_key UNIQUE (document_id, principal, allow_read)
);
CREATE INDEX kb_document_acl_document_idx ON kb_document_acl (document_id);

-- Verzeichnis-Anbindung je Organisation (Active Directory oder generisches LDAP).
CREATE TABLE directory_connection (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    kind character varying(20) NOT NULL,
    display_name character varying(200) NOT NULL,
    url character varying(500) NOT NULL,
    base_dn character varying(500) NOT NULL,
    bind_dn character varying(500) NOT NULL,
    bind_secret_cipher character varying(2000),
    user_filter character varying(500) NOT NULL,
    start_tls boolean NOT NULL,
    allow_plain_ldap boolean NOT NULL,
    login_enabled boolean NOT NULL,
    auto_provision boolean NOT NULL,
    enabled boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT directory_connection_pkey PRIMARY KEY (id),
    CONSTRAINT directory_connection_kind_check CHECK (kind IN ('AD', 'LDAP'))
);
CREATE INDEX directory_connection_org_idx ON directory_connection (org_id);

-- Eine Datenquelle füllt genau eine Wissensbasis, nur lesend.
CREATE TABLE data_source (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    knowledge_base_id bigint NOT NULL,
    kind character varying(20) NOT NULL,
    display_name character varying(200) NOT NULL,
    location character varying(1000) NOT NULL,
    username character varying(300),
    secret_cipher character varying(2000),
    include_patterns character varying(2000) NOT NULL,
    exclude_patterns character varying(2000) NOT NULL,
    max_file_bytes bigint NOT NULL,
    mirror_permissions boolean NOT NULL,
    interval_minutes integer NOT NULL,
    enabled boolean NOT NULL,
    last_run_started_at timestamp with time zone,
    last_run_finished_at timestamp with time zone,
    last_run_status character varying(20),
    last_run_message character varying(1000),
    files_seen integer NOT NULL,
    files_indexed integer NOT NULL,
    files_failed integer NOT NULL,
    created_by bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT data_source_pkey PRIMARY KEY (id),
    CONSTRAINT data_source_kind_check CHECK (kind IN ('LOCAL', 'SMB')),
    CONSTRAINT data_source_status_check CHECK (last_run_status IS NULL
        OR last_run_status IN ('RUNNING', 'OK', 'PARTIAL', 'FAILED'))
);
CREATE INDEX data_source_org_idx ON data_source (org_id);

-- Abgleichstand je Datei einer Quelle (Delta-Erkennung, Löschungen).
CREATE TABLE data_source_file (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    data_source_id bigint NOT NULL,
    relative_path character varying(2000) NOT NULL,
    document_id bigint,
    size_bytes bigint NOT NULL,
    modified_at timestamp with time zone NOT NULL,
    acl_fingerprint character varying(64) NOT NULL,
    last_error character varying(500),
    CONSTRAINT data_source_file_pkey PRIMARY KEY (id),
    CONSTRAINT data_source_file_path_key UNIQUE (data_source_id, relative_path)
);
CREATE INDEX data_source_file_document_idx ON data_source_file (document_id);
