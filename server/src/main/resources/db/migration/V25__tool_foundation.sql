-- 1) Risikoklasse je MCP-Werkzeug, ausschließlich vom Admin gesetzt (JSON-Objekt Name -> READ/WRITE/CRITICAL).
--    Bestehende Werkzeuge bleiben UNKLASSIFIZIERT und damit gesperrt; alte Freigaben werden nicht als READ übernommen.
ALTER TABLE mcp_server ADD COLUMN tool_risks character varying(20000);

-- 2) Zentrales Pflicht-Protokoll aller Werkzeugaufrufe (ohne Argumente/Ergebnisse), adapterunabhängig.
CREATE TABLE tool_call_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    called_at timestamp with time zone NOT NULL,
    user_id bigint NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    adapter character varying(32) NOT NULL,
    tool_id character varying(300) NOT NULL,
    source_id bigint,
    source_name character varying(120) NOT NULL,
    tool_name character varying(128) NOT NULL,
    risk character varying(16),
    duration_ms bigint NOT NULL,
    ok boolean NOT NULL,
    error character varying(300),
    CONSTRAINT tool_call_log_pkey PRIMARY KEY (id)
);
CREATE INDEX tool_call_log_time_idx ON tool_call_log (called_at);

-- Bisheriges MCP-Protokoll übernehmen (nur kopieren; mcp_call_log bleibt unverändert als Altbestand).
INSERT INTO tool_call_log (called_at, user_id, org_id, space_id, conversation_id, adapter, tool_id, source_id,
                           source_name, tool_name, risk, duration_ms, ok, error)
SELECT called_at, user_id, org_id, space_id, conversation_id, 'mcp',
       CONCAT('mcp:', CAST(server_id AS VARCHAR(20)), ':', tool_name), server_id, server_name, tool_name, NULL,
       duration_ms, ok, error
FROM mcp_call_log;
