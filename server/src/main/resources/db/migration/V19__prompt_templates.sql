-- Vorlagen / gespeicherte Fragen je Organisation oder Arbeitsbereich (PO-Freigabe 14.11.2026).
-- space_id NULL = für die ganze Organisation. Portable SQL (PostgreSQL + H2).
CREATE TABLE prompt_template (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id bigint NOT NULL,
    space_id bigint,
    title character varying(120) NOT NULL,
    body character varying(4000) NOT NULL,
    created_by bigint NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT prompt_template_pkey PRIMARY KEY (id)
);
CREATE INDEX prompt_template_org_idx ON prompt_template (org_id, space_id);
