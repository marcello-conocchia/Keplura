-- Chat-Produktivität: weitere Wissensbasen je Unterhaltung + angehängte Dateien.
-- Die primäre Wissensbasis bleibt chat_conversation.knowledge_base_id.

CREATE TABLE chat_conversation_kb (
    conversation_id   BIGINT NOT NULL,
    knowledge_base_id BIGINT NOT NULL,
    PRIMARY KEY (conversation_id, knowledge_base_id),
    CONSTRAINT fk_chat_conv_kb_conv FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_conv_kb_kb FOREIGN KEY (knowledge_base_id) REFERENCES knowledge_base (id) ON DELETE CASCADE
);

CREATE TABLE chat_attachment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    filename        VARCHAR(255) NOT NULL,
    text_content    VARCHAR(32000) NOT NULL,
    char_count      INTEGER NOT NULL,
    truncated       BOOLEAN NOT NULL,
    created_by      BIGINT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chat_attachment_conv FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id) ON DELETE CASCADE
);
CREATE INDEX ix_chat_attachment_conv ON chat_attachment (conversation_id);
