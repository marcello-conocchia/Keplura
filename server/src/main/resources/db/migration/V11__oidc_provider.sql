-- OIDC-M2-TAIL (docs/adr/0009 §2/§5): OIDC provider config rows + the
-- OIDC account link.
--
-- oidc_provider is deployment-level config on purpose (same posture as
-- ai_provider, ADR-0008 §3): NO org_id column — one corporate IdP per
-- installation; per-org identity would be new scope without a PO request.
--
-- Portability rules as in V1-V10: identity columns, timestamp(6) with time
-- zone, named constraints, no FKs (integrity lives in the service layer),
-- no partial indexes. "At most ONE active provider" is enforced via the
-- unique active_slot column (the ai_model default-slot trick: NULL unless
-- active, UNIQUE makes a double-active impossible even under a race).
--
-- client_secret_cipher stores AES-GCM ciphertext (Base64) produced by the
-- existing SecretCipher — the plaintext client secret NEVER exists in the
-- schema, a log line, or an API response (ADR-0008 §4 leak discipline).
-- NULL = public client / no secret set.

CREATE TABLE oidc_provider (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- operator-facing label ("Firmenkonto" etc.), never secret
    name character varying(200) NOT NULL,
    -- issuer URL; must equal the discovery document's issuer EXACTLY (ADR-0009 §4)
    issuer character varying(500) NOT NULL,
    -- OIDC discovery document URL (dialed SSRF-guarded at save + begin; §8)
    discovery_url character varying(500) NOT NULL,
    client_id character varying(200) NOT NULL,
    client_secret_cipher character varying(1000),
    -- retirement flag (no delete surface, same posture as ai_provider)
    active boolean NOT NULL DEFAULT TRUE,
    -- 1..300 seconds, same bounds as ai_provider.timeout_seconds
    timeout_seconds integer NOT NULL DEFAULT 15,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    -- NULL unless this row is THE active provider; unique guard copied from
    -- ai_model.default_slot (portable, H2 + PostgreSQL)
    active_slot bigint,
    CONSTRAINT oidc_provider_pkey PRIMARY KEY (id),
    CONSTRAINT oidc_provider_name_key UNIQUE (name),
    CONSTRAINT oidc_provider_timeout_check CHECK (timeout_seconds BETWEEN 1 AND 300),
    CONSTRAINT oidc_provider_active_slot_key UNIQUE (active_slot)
);

-- ADR-0009 §5: persistent account links. NO auto-provisioning: an OIDC
-- subject can only reach a user row that already exists AND was explicitly
-- linked — by the verified-email claim at callback time (insert here, the
-- service re-verifies email_verified) or in advance by an admin pairing.
-- UNIQUE(provider_id, subject): one corporate identity can never own two
-- accounts. provider_id is an INTEGER key, not an FK (repo posture: no FKs;
-- a deleted provider row is impossible anyway — active=false is the only
-- retirement verb, so links can never dangle on a vanished row). subject
-- length capped by the service at 200. Links are per-provider BY DESIGN:
-- retiring an IdP and wiring a new one must NEVER inherit the old provider's
-- links — a cross-provider sub collision could otherwise silently grant
-- access (ADR-0009 §5).
CREATE TABLE oidc_account_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider_id bigint NOT NULL,
    subject character varying(200) NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT oidc_account_link_pkey PRIMARY KEY (id),
    CONSTRAINT oidc_account_link_provider_subject_key UNIQUE (provider_id, subject)
);
